#[cfg(test)]
mod tests {
    use super::*;

    fn placeholders(s: &str) -> Vec<String> {
        let mut v: Vec<String> =
            s.split('{').skip(1).filter_map(|p| p.split_once('}').map(|(k, _)| k.to_string())).collect();
        v.sort();
        v
    }

    #[test]
    fn alle_sprachen_vollstaendig_und_platzhalter_gleich() {
        let en = EN.entries();
        for lang in Lang::ALL {
            for ((key, text), (_, en_text)) in lang.strings().entries().into_iter().zip(&en) {
                assert!(!text.trim().is_empty(), "{lang:?}.{key} ist leer");
                assert_eq!(placeholders(text), placeholders(en_text), "{lang:?}.{key}: Platzhalter weichen ab");
            }
        }
    }

    #[test]
    fn locale_codes() {
        assert_eq!(Lang::from_code("de-DE"), Some(Lang::De));
        assert_eq!(Lang::from_code("pt_BR.UTF-8"), Some(Lang::Pt));
        assert_eq!(Lang::from_code("EN"), Some(Lang::En));
        assert_eq!(Lang::from_code("uk-UA"), Some(Lang::Uk));
        assert_eq!(Lang::from_code("zh-CN"), None);
        assert_eq!(fill("Files: {n}", "n", 3), "Files: 3");
    }
}
