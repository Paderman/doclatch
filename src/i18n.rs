//! Übersetzungen. Englisch ist die Hauptsprache.
//!
//! Jede Sprache ist eine vollständige `Strings`-Struktur – fehlt ein Text, meldet das der Compiler.
//! Platzhalter in geschweiften Klammern (`{n}`, `{path}` …) werden mit [`fill`] ersetzt; ein Test
//! prüft, dass jede Übersetzung dieselben Platzhalter wie das Englische enthält.
//! Formulierungen sind bewusst als „Bezeichnung: Wert“ gehalten, damit keine Pluralregeln nötig sind.

#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
pub enum Lang {
    En,
    De,
    Fr,
    Es,
    It,
    Pt,
    Nl,
    Pl,
    Tr,
    Ru,
    Uk,
}

impl Lang {
    pub const ALL: [Lang; 11] =
        [Lang::En, Lang::De, Lang::Fr, Lang::Es, Lang::It, Lang::Pt, Lang::Nl, Lang::Pl, Lang::Tr, Lang::Ru, Lang::Uk];

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::De => "de",
            Lang::Fr => "fr",
            Lang::Es => "es",
            Lang::It => "it",
            Lang::Pt => "pt",
            Lang::Nl => "nl",
            Lang::Pl => "pl",
            Lang::Tr => "tr",
            Lang::Ru => "ru",
            Lang::Uk => "uk",
        }
    }

    /// Name der Sprache in der Sprache selbst (für die Auswahlliste).
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::De => "Deutsch",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::It => "Italiano",
            Lang::Pt => "Português",
            Lang::Nl => "Nederlands",
            Lang::Pl => "Polski",
            Lang::Tr => "Türkçe",
            Lang::Ru => "Русский",
            Lang::Uk => "Українська",
        }
    }

    /// Erkennt die Sprache aus einem Locale-Code wie `de-DE`, `pt_BR` oder `en`.
    pub fn from_code(code: &str) -> Option<Lang> {
        let primary = code.split(['-', '_', '.', '@']).next()?.to_ascii_lowercase();
        Lang::ALL.into_iter().find(|l| l.code() == primary)
    }

    /// Bevorzugte Systemsprache – erste unterstützte aus der Liste des Betriebssystems, sonst Englisch.
    pub fn detect() -> Lang {
        sys_locale::get_locales().find_map(|l| Lang::from_code(&l)).unwrap_or(Lang::En)
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Lang::En => &EN,
            Lang::De => &DE,
            Lang::Fr => &FR,
            Lang::Es => &ES,
            Lang::It => &IT,
            Lang::Pt => &PT,
            Lang::Nl => &NL,
            Lang::Pl => &PL,
            Lang::Tr => &TR,
            Lang::Ru => &RU,
            Lang::Uk => &UK,
        }
    }
}

/// Ersetzt einen Platzhalter, z. B. `fill(t.files_count, "n", 5)`.
pub fn fill(template: &str, key: &str, value: impl std::fmt::Display) -> String {
    template.replace(&format!("{{{key}}}"), &value.to_string())
}

macro_rules! strings {
    ($($field:ident),* $(,)?) => {
        pub struct Strings { $(pub $field: &'static str,)* }
        impl Strings {
            #[cfg(test)]
            pub fn entries(&self) -> Vec<(&'static str, &'static str)> {
                vec![$((stringify!($field), self.$field),)*]
            }
        }
    };
}

